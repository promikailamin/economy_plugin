package minecraft.economy;

import org.bukkit.Material;
import org.bukkit.entity.Player;
import org.bukkit.event.inventory.InventoryClickEvent;
import org.bukkit.inventory.ItemStack;
import org.bukkit.inventory.meta.ItemMeta;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

public final class MysteryGui {

    private static final int[] TIER_SLOTS = {10, 12, 14, 16, 18};

    private MysteryGui() {
    }

    private static MysteryShop shop() {
        return EconomyPlugin.get().mystery();
    }

    public static void open(Player player) {
        new Main(player).open();
    }

    public static void openResult(Player player, MysteryShop.Result result) {
        new ResultView(player, result).open();
    }

    private static ItemStack tierItem(Player player, MysteryShop shop, MysteryShop.Tier tier) {
        MysteryShop.Status status = shop.status(tier);
        boolean out = status.stock() <= 0;
        long cost = shop.cost(tier);
        List<String> lore = new ArrayList<>();
        lore.add("§7" + tier.description());
        lore.add("§7Cost: " + (EconomyData.getBalance(player) >= cost ? "§6" : "§c") + EconomyData.formatMoney(cost));
        lore.add("§7Stock: " + (out ? "§c0 §8(restock " + shop.restockText(tier) + ")"
                : "§a" + status.stock() + "§8/§7" + status.capacity()));
        lore.add("§7Jackpot chance: §d" + String.format(Locale.US, "%.1f", tier.jackpotChance() * 100) + "%");
        lore.add("§7Items: §fgear, crates, books, supplies");
        lore.add("§8-------------------------");
        lore.add(out ? "§c▶ Out of stock" : "§a▶ Click to open for " + EconomyData.formatMoney(cost));
        return EcoGui.item(tier.icon(), (out ? "§8" : "§d§l") + tier.label(), lore);
    }

    private static final class Main extends EcoGui {
        Main(Player player) {
            super(player, 6, "§dMystery Shop §8| §7AI fortune engine");
            MysteryShop shop = shop();
            if (shop == null) return;
            List<MysteryShop.Tier> tiers = shop.tiers();
            for (int i = 0; i < tiers.size() && i < TIER_SLOTS.length; i++) {
                inv.setItem(TIER_SLOTS[i], tierItem(player, shop, tiers.get(i)));
            }
            inv.setItem(4, item(Material.NETHER_STAR, "§d§lNeural Fortune Engine",
                    "§7Crates are generated by the market AI.",
                    "§7Each roll can be worse, fair or much better.",
                    "§7Return rate: §e" + percent(shop.returnRate()),
                    "§7Crates opened: §f" + shop.opens(),
                    "§7Biggest win: §6" + EconomyData.formatMoney(shop.biggestWin()),
                    "§7Dry streak: §f" + shop.dryStreak(player) + " §8(luck slowly builds)"));
            inv.setItem(BACK, item(Material.ARROW, "§c« Back", "§7Return to previous screen"));
            inv.setItem(48, item(Material.ENDER_EYE, "§b§lAuction House", "§7Browse live player and AI listings"));
            inv.setItem(HEAD, balanceHead(player));
            inv.setItem(50, item(Material.BEACON, "§b§lSmart Market", "§7Check AI stock and demand"));
            inv.setItem(51, item(Material.COMPARATOR, "§eRefresh", "§7Refresh stock and odds"));
            inv.setItem(CLOSE, item(Material.BARRIER, "§cClose", "§7Close this menu"));
            fillEmpty(inv, 0, 45, Material.BLACK_STAINED_GLASS_PANE);
            fillEmpty(inv, 45, 54, Material.GRAY_STAINED_GLASS_PANE);
        }

        @Override
        protected void handle(InventoryClickEvent e, int slot) {
            GuiHistoryManager.GuiState me = new GuiHistoryManager.GuiState("mystery");
            MysteryShop shop = shop();
            if (shop == null) return;
            for (int i = 0; i < TIER_SLOTS.length; i++) {
                if (TIER_SLOTS[i] == slot) {
                    List<MysteryShop.Tier> tiers = shop.tiers();
                    if (i >= tiers.size()) return;
                    MysteryShop.Result result = shop.open(player, tiers.get(i));
                    if (result != null) {
                        navigate(me, () -> openResult(player, result));
                    } else {
                        MysteryGui.open(player);
                    }
                    return;
                }
            }
            switch (slot) {
                case BACK -> back();
                case 48 -> navigate(me, () -> AuctionGui.open(player, 1));
                case 50 -> navigate(me, () -> AiMarketGui.open(player));
                case 51 -> MysteryGui.open(player);
                case CLOSE -> close();
                default -> {
                }
            }
        }
    }

    private static final class ResultView extends EcoGui {
        private final MysteryShop.Result result;

        ResultView(Player player, MysteryShop.Result result) {
            super(player, 3, result.jackpot() ? "§d§lJACKPOT §8| §7" + result.tier().label() : "§d" + result.tier().label());
            this.result = result;
            inv.setItem(13, prizeDisplay(result));
            inv.setItem(4, balanceHead(player));
            inv.setItem(11, item(Material.BARREL, "§eOpen another crate",
                    "§7" + result.tier().label() + " costs " + EconomyData.formatMoney(shop().cost(result.tier())),
                    "§7Stock: §f" + shop().status(result.tier()).stock()));
            inv.setItem(15, item(Material.CHEST, "§dMystery Shop", "§7Return to all crates"));
            inv.setItem(22, item(Material.BARRIER, "§cClose", "§7Take your prize and go"));
            fillEmpty(inv, 0, 27, Material.GRAY_STAINED_GLASS_PANE);
        }

        @Override
        protected void handle(InventoryClickEvent e, int slot) {
            switch (slot) {
                case 11 -> {
                    MysteryShop.Result next = shop().open(player, result.tier());
                    if (next != null) {
                        new ResultView(player, next).open();
                    } else {
                        MysteryGui.open(player);
                    }
                }
                case 15 -> MysteryGui.open(player);
                case 22 -> close();
                default -> {
                }
            }
        }

        private static ItemStack prizeDisplay(MysteryShop.Result result) {
            ItemStack primary = result.primary();
            if (primary == null) return EcoGui.item(Material.CHEST, "§7Nothing?");
            ItemStack display = primary.clone();
            ItemMeta meta = display.getItemMeta();
            if (meta != null) {
                List<String> lore = meta.getLore() == null ? new ArrayList<>() : new ArrayList<>(meta.getLore());
                lore.add("§8-------------------------");
                lore.add("§7Prize value: §6" + EconomyData.formatMoney(result.value()));
                if (result.jackpot()) lore.add("§d§lJACKPOT! The engine paid out big.");
                if (result.items().size() > 1) {
                    lore.add("§7Also won: §f" + (result.items().size() - 1) + " more item(s)");
                    for (ItemStack item : result.items()) {
                        if (item == primary) continue;
                        lore.add("§8- §7" + item.getAmount() + "x " + AuctionHouse.prettyName(item));
                    }
                }
                meta.setLore(lore);
                display.setItemMeta(meta);
            }
            return display;
        }
    }

    private static String percent(double value) {
        return Math.round(value * 100) + "%";
    }
}
